a=blank();d=ImageDraw.Draw(a)
d.ellipse((220,120,550,470),fill=skin,outline=ink,width=5)
d.ellipse((204,255,238,320),fill=skin,outline=ink,width=4)
d.ellipse((532,255,566,320),fill=skin,outline=ink,width=4)
