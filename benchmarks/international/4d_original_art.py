d.line((385,255,374,305),fill=ink,width=3)
d.arc((358,300,392,328),20,150,fill=ink,width=3)
for rect in [(258,302,334,352),(434,302,510,352)]:
 b=blank();ImageDraw.Draw(b).ellipse(rect,fill=(250,160,180,85))
 a=Image.alpha_composite(a,b.filter(ImageFilter.GaussianBlur(8)))
b=blank();ImageDraw.Draw(b).ellipse((270,155,360,260),fill=(255,255,255,28))
a=Image.alpha_composite(a,b.filter(ImageFilter.GaussianBlur(20)));save(a,'face')
a=blank();d=ImageDraw.Draw(a)
for bx in [(275,246,360,290),(408,246,493,290)]:
 d.pieslice(bx,180,360,fill=(255,255,255,255),outline=ink,width=3)
 d.arc((bx[0],bx[1]-2,bx[2],bx[3]+10),180,360,fill=ink,width=4)
save(a,'eyewhite')
a=blank();d=ImageDraw.Draw(a)
for cx in [317,450]:
 d.ellipse((cx-20,246,cx+20,286),fill=iris,outline=ink,width=2)
 d.ellipse((cx-12,252,cx+12,278),fill=iris2)
